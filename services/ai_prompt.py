from typing import Optional


class AIPromptBuilder:
    """
    네이버 블로그 게시글 맥락을 기반으로 긍정적이고 안전한 칭찬형 댓글을 작성하도록
    지시하는 프롬프트를 생성합니다 (Human-Like Composer v3.1 Safe Policy).
    """
    @classmethod
    def build(cls, title: str, excerpt: str = "", style: str = "warm_short") -> str:
        title_s = title.strip() if title else "(제목 없음)"
        excerpt_s = excerpt.strip() if excerpt else ""

        if excerpt_s:
            prompt = f"""아래 네이버 블로그 글에 어울리는 짧고 따뜻한 칭찬 댓글 하나만 써줘.

댓글 원칙:
- 친근하고 따뜻한 한국어 대화체 (1~2문장 정도로 간결하게)
- 글에서 실제로 보이는 메뉴, 장소, 공간, 사진, 분위기 중 하나를 자연스럽게 칭찬
- "저도 한번 가보고 싶네요 :)", "다음에 가면 저도 꼭 먹어보고 싶어요" 처럼 자연스러운 취향이나 미래 의향 표현 환영
- ⚠ 절대 금지 규칙:
  1. 상대의 선택을 비교/평가하는 표현 금지 ("저라면", "제가 보기에는" 등)
  2. 부정적으로 들릴 수 있는 단어 금지 ("생각보다", "의외로", "그나마", "나쁘지 않네요", "호불호" 등)
  3. 외모/신체 평가 금지
  4. 실제로 방문/구매/사용한 것처럼 거짓 과거 경험 지어내기 금지 ("저도 가봤는데", "저도 먹어봤는데" X)
  5. 뻔한 매크로 문구 금지 ("유익한 정보", "잘 보고 갑니다", "인상적입니다", "좋은 정보네요")
  6. 사적인 질문이나 억지 질문 금지
- 이모지는 0~1개 정도만 자연스럽게 사용
- 오직 '댓글 본문'만 출력

제목:
{title_s}

본문 일부:
{excerpt_s}"""
        else:
            prompt = f"""아래 네이버 블로그 글에 어울리는 짧고 따뜻한 칭찬 댓글 하나만 써줘.

댓글 원칙:
- 친근하고 따뜻한 한국어 대화체 (1~2문장 간결하게)
- 제목의 키워드에 맞춰 가볍고 기분 좋은 칭찬
- "저라면", "생각보다", "의외로", "유익한 정보", "잘 보고 갑니다" 등 금지
- 거짓 과거 경험 지어내기 금지
- 오직 '댓글 본문'만 출력

제목:
{title_s}"""

        return prompt
