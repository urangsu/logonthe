import uuid
from typing import Optional


class AIPromptBuilder:
    """
    네이버 블로그 게시글 맥락 기반 담백한 인간형 댓글 생성 프롬프트 빌더 (v6.0 Natural Comment)
    - 캐릭터 연기(찐이웃, 취저, 못참죠, 더라구요) 완전 삭제
    - 요약문 및 보고서형 연결어(전체적으로, 특히, 무엇보다, 인상적이네요, 알찬 정보) 원천 금지
    - 본문 1~2개 세부 디테일에 바로 반응하는 담백한 35~75자 1~2문장 유도
    """

    @classmethod
    def build(
        cls,
        title: str,
        excerpt: str = "",
        style: str = "warm_short",
        request_id: Optional[str] = None
    ) -> str:
        req_id = request_id or uuid.uuid4().hex[:8]
        title_s = title.strip() if title else "(제목 없음)"
        excerpt_s = excerpt.strip() if excerpt else ""

        if excerpt_s:
            prompt = f"""너는 20~30대 네이버 블로거가 다른 사람의 글을 읽고 짧게 댓글을 남기는 상황이다.
광고문구나 AI가 정리한 문장처럼 쓰지 말고, 실제 사람이 읽다가 눈에 들어온 부분에 바로 반응하듯 써라.

[작성 가이드 및 절대 금지 규칙]
1. 길이 제한: 공백 포함 100자 이하 (권장 35~75자). 담백한 한두 문장이면 충분하다.
2. 디테일 반응: 글의 모든 내용을 요약하지 말고, 본문에서 실제로 나온 메뉴·장소·분위기·경험·팁 중 눈에 들어온 한두 가지만 자연스럽게 언급한다.
3. 요약/나열식 문장 금지: "A도 좋고 B도 좋고 C까지 좋네요" 같은 나열식 문장이나 "전체적으로", "특히", "무엇보다", "인상적이네요", "알찬 정보네요", "유익한 정보"처럼 AI가 보고서식으로 정리하는 표현은 절대 쓰지 않는다.
4. 담백한 말투 사용: "저도 한번 먹어보고 싶네요", "이 메뉴도 궁금하네요", "사진 보니까 여기 가보고 싶어요", "이 조합 맛있어 보이네요" 정도의 자연스러운 말투를 사용한다.
5. 과장/인터넷 유행어 금지: "꼭", "반드시", "무조건", "대박", "취저", "취향저격", "못 참죠", "강추", "구매각", "방문각"은 사용하지 않는다.
6. 이모지 및 웃음 문자 금지: "ㅎㅎ", "ㅋㅋ", "^^", ":)", ":D", "ㅠㅠ" 및 모든 그림 이모지와 기호는 사용하지 않는다.
7. 거짓 경험 금지: 직접 경험하지 않은 일을 경험한 것처럼 "저도 가봤는데", "저도 먹어봤는데", "써보니", "~더라구요"라고 쓰지 않는다.
8. 질문을 억지로 만들지 않는다.

[출력 형식 - 중요]
설명, 인사말, 따옴표, 마크다운 없이 오직 아래 마커 사이에 최종 댓글 한 개만 출력해:
[[CMT:{req_id}]]
댓글 본문
[[/CMT]]

제목: {title_s}
본문 요약:
{excerpt_s}"""
        else:
            prompt = f"""너는 20~30대 네이버 블로거가 다른 사람의 글을 읽고 짧게 댓글을 남기는 상황이다.
광고문구나 AI 요약처럼 쓰지 말고, 아래 제목에 맞춰 자연스럽고 담백한 1~2문장의 댓글을 작성해줘.

[작성 원칙]
1. 길이: 공백 포함 35~75자 내외 (1~2문장).
2. 요약이나 보고서식 말투 금지 ("전체적으로", "인상적이네요", "유익한 정보" 금지).
3. "꼭", "대박", "취저", "강추", "~더라구요" 및 거짓 경험 금지.
4. "ㅎㅎ", "ㅋㅋ", "^^", ":)" 및 모든 이모지/이모티콘 사용 금지.
5. 설명, 인사, 따옴표 없이 오직 아래 마커 사이에만 출력.

[[CMT:{req_id}]]
댓글 본문
[[/CMT]]

제목: {title_s}"""

        return prompt
