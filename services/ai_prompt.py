import uuid
from typing import Optional


class AIPromptBuilder:
    """
    네이버 블로그 게시글 맥락을 기반으로 긍정적이고 안전한 인간형 칭찬 댓글 생성을 위한 프롬프트 빌더 (v5.0)
    - Request ID 마커([[CMT:{id}]]...[[/CMT]]) 지원으로 신선한 응답 식별
    - 본문 세부 디테일 앵커(사이드 메뉴, 팁, 분위기) 콕 집어 언급 유도
    - 거짓 과거 경험 및 매크로 어휘 원천 차단
    """

    @classmethod
    def build(
        cls,
        title: str,
        excerpt: str = "",
        style: str = "warm_short",
        request_id: Optional[str] = None
    ) -> str:
        req_id = request_id or uuid.uuid4().hex[:8]
        title_s = title.strip() if title else "(제목 없음)"
        excerpt_s = excerpt.strip() if excerpt else ""

        if excerpt_s:
            prompt = f"""너는 네이버 블로그 글을 재미있게 읽고 댓글을 남기는 2030 친근한 찐이웃 블로거야.
아래 블로그 글의 본문 내용 중 '구체적인 디테일(세부 메뉴, 사이드 구성, 팁, 공간 분위기 등)' 1~2개를 콕 집어 언급하며 자연스럽고 따뜻한 댓글 한 개를 작성해줘.

[작성 원칙 및 절대 금지 규칙]
1. 실제 네이버 블로거들의 자연스러운 구어체 (~네요, ~더라구요!, ~못 참죠, ~취저예요 등)
2. 글에 나오는 구체적인 요소(예: 소세지/감튀 조합, 오픈런 팁, 깔끔한 오차즈케 등)를 자연스럽게 칭찬
3. 길이 제한: 공백 포함 100자 이하 (권장 35~75자 정도로 간결하게)
4. 거짓 과거 경험 금지 ("저도 가봤는데", "저도 써봤는데" X -> "저도 나중에 가보고 싶네요!", "지도에 저장해둬야겠어요" O)
5. '꼭' 단어 절대 금지 ("꼭 가봐야", "꼭 먹어", "꼭 가보고" 등 '꼭' 단어는 절대 넣지 마세요)
6. 뻔한 매크로 금지 ("유익한 정보 감사합니다", "잘 보고 갑니다", "인상적입니다", "좋은 포스팅이네요" 절대 금지)
7. 비교/평가성 단어 금지 ("생각보다", "의외로", "그나마", "나쁘지 않네요", "저라면")
8. 이모지(이모티콘) 및 웃는 문자 금지 (모든 이모지, 'ㅎㅎ', 'ㅋㅋ', '^^', ':)', ':D' 등 절대 사용 금지. 깔끔한 문장 부호로만 마무리)

[출력 형식 - 중요]
설명이나 인사말, 따옴표 없이 오직 아래 마커 사이에 최종 댓글 한 개만 출력해:
[[CMT:{req_id}]]
댓글 본문
[[/CMT]]

제목: {title_s}
본문 요약:
{excerpt_s}"""
        else:
            prompt = f"""너는 네이버 블로그 글을 읽고 댓글을 남기는 2030 친근한 찐이웃 블로거야.
아래 제목에 맞춰 자연스럽고 기분 좋은 1~2문장의 따뜻한 칭찬 댓글을 작성해줘.

[작성 원칙]
1. 친근한 네이버 블로거 구어체 (~네요, ~더라구요!)
2. '꼭' 단어 및 거짓 과거 경험/매크로 어휘 금지
3. 이모지 및 'ㅎㅎ', 'ㅋㅋ', '^^', ':)' 등 웃는 이모티콘 문자 절대 사용 금지
4. 설명/따옴표 없이 오직 아래 마커 사이에만 출력

[[CMT:{req_id}]]
댓글 본문
[[/CMT]]

제목: {title_s}"""

        return prompt
