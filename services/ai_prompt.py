from typing import Optional


class AIPromptBuilder:
    """
    네이버 블로그 게시글 맥락(제목 + 본문 일부)을 기반으로
    짧고 정감 있는 칭찬형 댓글을 작성하도록 지시하는 프롬프트를 생성합니다.
    """
    @classmethod
    def build(cls, title: str, excerpt: str = "", style: str = "warm_short") -> str:
        title_s = title.strip() if title else "(제목 없음)"
        excerpt_s = excerpt.strip() if excerpt else ""

        if excerpt_s:
            prompt = f"""아래 네이버 블로그 글에 어울리는 짧고 정감 있는 댓글 하나만 써줘.

댓글 느낌:
- 친근하고 따뜻한 한국어 대화체
- 1~2문장 정도로 간결하고 짧게 (부담 없는 길이)
- 글에서 실제로 보이는 장소, 메뉴, 분위기, 사진, 경험 중 하나를 자연스럽게 한 번 언급
- 분석하듯 평가하지 말고 가볍게 칭찬하거나 공감하는 느낌
- 너무 딱딱하거나 어색한 문어체 피하기
- "유익한 정보 감사합니다", "좋은 정보네요", "포스팅 잘 보고 갑니다" 같은 뻔한 매크로 문구는 절대 쓰지 않기
- 억지 질문은 하지 말 것 (질문 금지)
- 과장된 감탄 금지
- 이모지는 0~1개 정도만 자연스럽게 사용
- 위 설명이나 인사말 없이 오직 '댓글 본문'만 출력

예시 느낌 (문장을 그대로 베끼지 말고 글 내용에 맞게 새로 작성할 것):
“분위기가 정말 편안해 보여서 저도 한번 가보고 싶네요 :)”
“사진 보니까 메뉴가 진짜 맛있어 보여요. 조합도 너무 좋네요!”
“산책하기 정말 좋아 보이네요. 사진도 편안한 느낌이라 좋았어요.”

제목:
{title_s}

본문 일부:
{excerpt_s}"""
        else:
            prompt = f"""아래 네이버 블로그 글에 어울리는 짧고 정감 있는 댓글 하나만 써줘.

댓글 느낌:
- 친근하고 따뜻한 한국어 대화체
- 1~2문장 정도로 간결하고 짧게
- 본문이 없으므로 제목에 없는 구체적인 사실을 지어내지 말고 제목의 키워드에 맞춰 가볍게 공감/칭찬
- "유익한 정보 감사합니다", "잘 보고 갑니다" 같은 뻔한 문구 금지
- 질문 금지
- 오직 '댓글 본문'만 출력

제목:
{title_s}"""

        return prompt
