        for title, excerpt, expected_category in self.FIXTURES:
            res = ContextualDraftEngine.generate(title, excerpt)
            # 1. 텍스트 길이 및 안전성 검증
            self.assertTrue(len(res.body) >= 15, f"Comment too short for '{title}': '{res.body}'")
            self.assertTrue(len(res.body) <= 100, f"Comment too long for '{title}': '{res.body}'")

            # 2. 금지 패턴 검증
            cand = CommentCandidate(
                body=res.body, category=res.category, reaction_intent=res.reaction_intent,
                first_person_intent=res.intent, subject=res.subject, template_id=res.template_id
            )
            valid, reason = PositiveSafetyValidator.validate_candidate(cand)
            self.assertTrue(valid, f"PositiveSafetyValidator rejected comment '{res.body}' for post '{title}': {reason}")

            # 3. 중요 Adversarial 케이스의 카테고리 매칭 검증
            if "스폰지밥" in title:
                self.assertEqual(res.category, "HOBBY_GOODS", f"Wrong category for '{title}': {res.category}")


